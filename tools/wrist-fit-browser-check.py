from playwright.sync_api import sync_playwright
from pathlib import Path
from wrist_fit_offline_harness import load
import json, os, shutil, tempfile
OUT=Path(os.environ.get('WATCHIFY_QA_OUTPUT', str(Path(tempfile.gettempdir())/'watchify-wrist-fit-qa')))
OUT.mkdir(parents=True,exist_ok=True)
checks=[];errors=[];console=[];requests=[]
def check(name,condition=True,details=None):
    if not condition: raise AssertionError(name+': '+str(details))
    checks.append({'name':name,'passed':True,**({'details':details} if details else {})})
def open_fit(page):
    page.get_by_role('button',name='See it on your wrist',exact=True).click()
    page.wait_for_timeout(240)
def change_route(page,route):
    page.evaluate('(route)=>{location.hash=route}',route)
    page.wait_for_timeout(80)
def screenshot(page,name,full=False):
    page.screenshot(path=str(OUT/name),full_page=full,animations='disabled')
def inside_viewport(page):
    return page.evaluate('''()=>{const b=document.querySelector('#modal').getBoundingClientRect();return b.left>=-1&&b.right<=innerWidth+1&&b.top>=-1&&b.bottom<=innerHeight+1}''')
with sync_playwright() as p:
    launch={'headless':True}
    executable=os.environ.get('WATCHIFY_QA_BROWSER') or shutil.which('chromium') or shutil.which('chromium-browser')
    if executable: launch['executable_path']=executable
    if hasattr(os,'geteuid') and os.geteuid()==0: launch['args']=['--no-sandbox']
    b=p.chromium.launch(**launch)
    desktop=b.new_page(viewport={'width':1440,'height':1000},device_scale_factor=1)
    desktop.on('pageerror',lambda e:errors.append(str(e)))
    desktop.on('console',lambda m:console.append(m.text) if m.type=='error' else None)
    desktop.on('request',lambda r:requests.append(r.url))
    load(desktop,'#explore')
    check('No simulator button on catalogue or new top-level navigation',desktop.locator('[data-action="wrist-fit"]').count()==0)
    check('Trade remains absent from the header',desktop.locator('#header').get_by_text('Trade',exact=True).count()==0)
    desktop.locator('a[href="#watch/datejust"]').first.click()
    desktop.get_by_role('button',name='See it on your wrist',exact=True).wait_for(state='visible',timeout=3000)
    check('Opening the listing exposes the contextual button',desktop.get_by_role('button',name='See it on your wrist',exact=True).count()==1)
    screenshot(desktop,'listing-desktop.png',True)
    open_fit(desktop)
    check('Native modal opens',desktop.locator('#modal').evaluate('(m)=>m.open'))
    check('Input receives initial focus',desktop.locator('#wf-circumference').evaluate('(e)=>document.activeElement===e'))
    check('No assumed starting wrist size',desktop.locator('#wf-circumference').input_value()=='' and desktop.locator('.wf-illustration').count()==0)
    screenshot(desktop,'modal-empty.png')
    box=desktop.locator('#modal').bounding_box()
    check('Desktop dialog is short and rectangular',box['width']>1.6*box['height'] and box['height']<=460,box)
    before=len(requests)
    desktop.locator('#wf-circumference').fill('16,5')
    check('Comma decimal produces a live preview',desktop.locator('.wf-illustration').get_attribute('data-wrist-cm')=='16.5')
    check('Uses the selected 41 mm Datejust listing',desktop.locator('.wf-illustration').get_attribute('data-case-width-mm')=='41')
    ratio16=desktop.locator('.wf-illustration').evaluate('(e)=>Number(e.dataset.caseWidthPx)/Number(e.dataset.wristWidthPx)')
    desktop.locator('#wf-circumference').fill('18')
    ratio18=desktop.locator('.wf-illustration').evaluate('(e)=>Number(e.dataset.caseWidthPx)/Number(e.dataset.wristWidthPx)')
    check('Larger wrist reduces relative watch size',ratio18<ratio16)
    for value in ['5.5','-16','31','16cm','1e1']:
        desktop.locator('#wf-circumference').fill(value)
        check('Invalid input clears stale preview: '+value,desktop.locator('.wf-illustration').count()==0 and desktop.locator('#wf-circumference').get_attribute('aria-invalid')=='true')
    desktop.locator('#wf-circumference').fill('')
    check('Clearing input clears preview and error',desktop.locator('.wf-illustration').count()==0 and desktop.locator('#wf-error').inner_text()=='')
    desktop.locator('#wf-circumference').press('Enter')
    check('Submitting an empty field explains the missing measurement',desktop.locator('#wf-error').inner_text()!='')
    desktop.locator('#wf-circumference').fill('16.5')
    check('Valid input recovers from errors',desktop.locator('#wf-error').inner_text()=='' and desktop.locator('.wf-illustration').count()==1)
    check('Input and rendering make no network requests',len(requests)==before)
    desktop.keyboard.press('Tab')
    check('Tab wraps to close instead of background',desktop.locator('[aria-label="Close dialog"]').evaluate('(e)=>document.activeElement===e'))
    desktop.keyboard.press('Shift+Tab')
    check('Shift+Tab wraps to the input',desktop.locator('#wf-circumference').evaluate('(e)=>document.activeElement===e'))
    screenshot(desktop,'modal-desktop.png')
    desktop.keyboard.press('Escape');desktop.wait_for_timeout(40)
    check('Escape closes and restores button focus',not desktop.locator('#modal').evaluate('(e)=>e.open') and desktop.locator('[data-action="wrist-fit"]').evaluate('(e)=>document.activeElement===e'))
    open_fit(desktop)
    check('Same-tab reopening retains only the last valid circumference',desktop.locator('#wf-circumference').input_value()=='16.5')
    desktop.locator('.wf-preview-label').click()
    check('Clicking inside does not close the modal',desktop.locator('#modal').evaluate('(e)=>e.open'))
    desktop.mouse.click(30,30);desktop.wait_for_timeout(30)
    check('Backdrop click closes',not desktop.locator('#modal').evaluate('(e)=>e.open'))
    open_fit(desktop)
    desktop.get_by_role('button',name='Close dialog',exact=True).click();desktop.wait_for_timeout(20)
    check('Close control restores button focus',desktop.locator('[data-action="wrist-fit"]').evaluate('(e)=>document.activeElement===e'))
    # Force close+reopen in the same task to exercise a queued native close event.
    open_fit(desktop)
    desktop.evaluate('''()=>{document.querySelector('[data-action="close-modal"]').click();document.querySelector('[data-action="wrist-fit"]').click()}''')
    desktop.wait_for_timeout(100)
    desktop.locator('#wf-circumference').fill('18.25')
    check('Rapid close/reopen leaves live handlers working',desktop.locator('.wf-illustration').get_attribute('data-wrist-cm')=='18.25')
    desktop.keyboard.press('Escape');desktop.wait_for_timeout(30)
    for watch_id,expected in [('submariner','41'),('santos','35.1'),('datejust','41'),('speedmaster','42'),('black-bay','39'),('gmt-pepsi','40'),('cartier-tank','25.5'),('royal-oak','41')]:
        change_route(desktop,'#watch/'+watch_id)
        open_fit(desktop)
        check('Selected watch data is fresh: '+watch_id,desktop.locator('.wf-body').get_attribute('data-watch-id')==watch_id and desktop.locator('.wf-illustration').get_attribute('data-case-width-mm')==expected)
        if watch_id=='cartier-tank':
            check('Tank uses 25.5 mm width and 33.7 mm height',desktop.locator('.wf-illustration').get_attribute('data-case-height-mm')=='33.7')
            screenshot(desktop,'modal-rectangular.png')
        desktop.keyboard.press('Escape');desktop.wait_for_timeout(20)
    # Reopening a different existing modal must not retain the fit disclaimer.
    change_route(desktop,'#watch/datejust')
    desktop.get_by_role('button',name='Make an offer',exact=True).click()
    check('Existing offer modal still works without stale description',desktop.locator('#offer-form').count()==1 and desktop.locator('#modal').get_attribute('aria-describedby') is None and 'wrist-fit-modal' not in desktop.locator('#modal').get_attribute('class'))
    desktop.keyboard.press('Escape')
    for route in ['#sell','#account/listings','#account/messages','#account/orders','#account/analytics','#account/reviews','#account/accounting']:
        change_route(desktop,route)
        check('Existing screen renders: '+route,len(desktop.locator('#main').inner_text())>60 and 'We couldn’t find' not in desktop.locator('#main').inner_text())
    check('No new app runtime or console errors',not errors and not console,{'errors':errors,'console':console})
    # New tabs do not persist body measurements.
    clean=b.new_page(viewport={'width':1280,'height':800})
    load(clean)
    open_fit(clean)
    check('New tab has no stored wrist measurement',clean.locator('#wf-circumference').input_value()=='')
    clean.close()
    # Missing dimensions are tested with a modified fixture, not a fallback size.
    missing=b.new_page(viewport={'width':1280,'height':800})
    load(missing,mutate_data="() => { WatchifyData.watches.find(w=>w.id==='datejust').size='To be confirmed'; }")
    check('Missing case dimensions disable the entry without a fake size',missing.get_by_role('button',name='Wrist preview unavailable').is_disabled() and missing.locator('[data-action="wrist-fit"]').count()==0)
    missing.close()
    for width,height in [(390,844),(320,568),(844,390)]:
        page=b.new_page(viewport={'width':width,'height':height},device_scale_factor=1,is_mobile=True,has_touch=True,reduced_motion='reduce')
        page.on('pageerror',lambda e:errors.append(str(e)))
        load(page)
        open_fit(page)
        page.locator('#wf-circumference').fill('16.5')
        check(f'Modal stays inside {width}×{height} viewport',inside_viewport(page),page.locator('#modal').bounding_box())
        check(f'No horizontal modal or page overflow at {width} px',page.evaluate('''()=>{const m=document.querySelector('#modal');return document.documentElement.scrollWidth<=innerWidth && m.scrollWidth<=m.clientWidth+1}'''))
        check(f'Controls remain usable at {width} px',page.locator('#wf-circumference').is_visible() and page.locator('.wf-illustration').count()==1)
        if width==390:screenshot(page,'modal-mobile.png')
        if width==320:screenshot(page,'modal-small-mobile.png')
        if width==844:screenshot(page,'modal-landscape.png')
        check(f'Reduced-motion removes dialog animation at {width} px',page.locator('#modal').evaluate("e=>getComputedStyle(e).animationName==='none'"))
        page.close()
    check('All browser checks ended without uncaught runtime errors',not errors,errors)
    report={'mode':'Offline Chromium DOM harness. Unmodified packaged JavaScript/CSS; image paths hydrated from local assets. Provider transport omitted. No live backend, CSP or production-provider verification claimed.','checks':checks,'count':len(checks),'errors':errors,'consoleErrors':console}
    (OUT/'browser-report.json').write_text(json.dumps(report,indent=2,ensure_ascii=False))
    print(json.dumps({'passed':len(checks),'errors':errors,'console':console},indent=2))
    b.close()
